-- =============================================================================
-- 20-fix-menu-icon-name.sql · 增量：修正失效的菜单图标名
-- =============================================================================
-- 缺陷来源（2026-11-01 管理端截图标注「所有菜单都没有图标」的收尾项）：
--   切换到离线图标集（VITE_GLOB_ICONIFY_USE_TYPE=local）后，91 个菜单图标正常，
--   唯独上游「关于」菜单（sys/about/index）仍是空心圆点 —— 因为它的图标名已经失效。
--
-- 根因：
--   上游基座 SQL（db/jeecg-study-mysql.sql:8241）里「关于」菜单的 icon 写的是
--     simple-icons:about-dot-me
--   而 iconify 的 simple-icons 集合里这个图标的名字是
--     simple-icons:aboutdotme        （simple-icons v10 起去掉了名字里的连字符）
--   图标集合里没有 about-dot-me → 离线打包时拿不到、在线拉取时 404，
--   两种模式下都只能渲染成占位空心圆点。
--
-- 为什么走增量脚本而不是改上游 SQL：
--   铁律 2「变更走增量脚本，不改历史脚本」。01-平台库初始化.sql 是上游基座 SQL 的拷贝，
--   属于历史脚本；本脚本在新环境按顺序执行后即生效，重复执行不报错。
--
-- 幂等：UPDATE 的 WHERE 命中不到行时不做任何事，重复执行结果一致。
-- =============================================================================

-- 「关于」菜单：图标名修正为 simple-icons 集合里的真实名字
UPDATE `sys_permission`
SET `icon` = 'simple-icons:aboutdotme'
WHERE `icon` = 'simple-icons:about-dot-me';
