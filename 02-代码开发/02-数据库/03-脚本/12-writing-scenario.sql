USE `jeecg-study`;

-- ------------------------------------------------------------------
-- 建表：写作情境库（内容表，全局共享）
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `study_writing_scenario` (
  `id`                varchar(32)  NOT NULL COMMENT '主键',
  `scenario_code`     varchar(32)  NOT NULL COMMENT '业务ID SEED-SCN-{主题码}-{序号}',
  `theme_code`        varchar(32)  NOT NULL COMMENT '主题编码(PERSIST/GROWTH/TRUST/LOSS/CHOICE/FIRSTTIME)',
  `theme_name`        varchar(64)  NOT NULL COMMENT '主题名称(如 坚持)',
  `title`             varchar(128) NOT NULL COMMENT '情境标题(处境一句话,不是金句)',
  `situation_desc`    text         NOT NULL COMMENT '处境描述(时间/地点/人物/阻力)',
  `age_stage`         varchar(32)  NOT NULL COMMENT '年龄段(如 小学中年级)',
  `age_min`           tinyint      NOT NULL DEFAULT 6 COMMENT '年龄下限',
  `age_max`           tinyint      NOT NULL DEFAULT 15 COMMENT '年龄上限',
  `detail_clue`       text         DEFAULT NULL COMMENT '细节线索(JSON数组文本,只给可观察的物与动作)',
  `stage_code`        varchar(16)  NOT NULL DEFAULT 'G3' COMMENT '适用学段 G1..G9',
  `genre`             varchar(32)  DEFAULT NULL COMMENT '适用文体(写事/写人/写物/写景/抒情)',
  `difficulty`        tinyint      NOT NULL DEFAULT 1 COMMENT '难度层级 1..5',
  `prompt_question`   varchar(512) DEFAULT NULL COMMENT '写作提示题(引导填自己的经历)',
  `restriction_note`  varchar(512) DEFAULT NULL COMMENT '限制条件(如 只写自己身上发生过的事)',
  `forbidden_words`   varchar(512) DEFAULT NULL COMMENT '禁用提示(禁止写成金句/禁止抄范文)',
  `order_weight`      int          NOT NULL DEFAULT 100 COMMENT '中性排序权重(同主题内的呈现先后)',
  `source_ref`        varchar(256) DEFAULT NULL COMMENT '出处(自编情境)',
  `copyright_type`    varchar(16)  NOT NULL DEFAULT 'SELF' COMMENT '版权类型 SELF/PUBLIC/LICENSE',
  `status`            tinyint      NOT NULL DEFAULT 1 COMMENT '状态 1启用 0停用',
  `del_flag`          tinyint      NOT NULL DEFAULT 0 COMMENT '删除标记 0正常 1删除',
  `create_by`         varchar(50)  DEFAULT NULL COMMENT '创建人',
  `create_time`       datetime     DEFAULT NULL COMMENT '创建时间',
  `update_by`         varchar(50)  DEFAULT NULL COMMENT '更新人',
  `update_time`       datetime     DEFAULT NULL COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_scenario_code` (`scenario_code`),
  KEY `idx_scn_theme` (`theme_code`, `status`, `order_weight`),
  KEY `idx_scn_stage` (`stage_code`, `status`),
  KEY `idx_scn_age` (`age_min`, `age_max`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='语文写作情境库(给处境不给金句,内容表全局共享)';

